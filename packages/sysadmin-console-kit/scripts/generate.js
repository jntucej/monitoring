// ---------------------------------------------------------------------------
// Path planning
// ---------------------------------------------------------------------------

/** Compute the file set that must exist for one page (command-center is skipped). */
function pageFiles(cat, p) {
  if (p.id === 'command-center') return [];
  const root = repoRoot();
  const route = p.route || '';
  const pageDir = route || p.id;
  return [
    path.join(root, 'src', 'app', '(sysadmin)', 'sysadmin', pageDir, 'page.tsx'),
    path.join(
      root,
      'src',
      'components',
      'sysadmin',
      'domains',
      cat.id,
      `${pascal(p.id)}Content.tsx`
    ),
    path.join(
      root,
      'src',
      'components',
      'sysadmin',
      'domains',
      cat.id,
      `${pascal(p.id)}Drawer.tsx`
    ),
    path.join(
      root,
      'src',
      'components',
      'sysadmin',
      'domains',
      cat.id,
      'types.ts'
    ),
    path.join(
      root,
      'src',
      'app',
      'api',
      'admin',
      cat.id,
      p.id,
      'overview',
      'route.ts'
    ),
  ];
}

/** Render content for a specific file given its path. */
function renderFor(file, cat, p) {
  const base = path.basename(file);
  const PascalId = pascal(p.id);
  if (base === 'page.tsx') return pageTemplate(cat, p);
  if (base === `${PascalId}Content.tsx`) return contentTemplate(cat, p);
  if (base === `${PascalId}Drawer.tsx`) return drawerTemplate(cat, p);
  if (base === 'types.ts') return typesTemplate(cat, p);
  if (base === 'route.ts') return apiRouteTemplate(cat, p);
  throw new Error(`No template for ${file}`);
}

function allPages(manifest) {
  const out = [];
  for (const cat of manifest.categories || []) {
    for (const p of cat.pages || []) out.push({ cat, p });
  }
  return out;
}

// ---------------------------------------------------------------------------
// Command: check
// ---------------------------------------------------------------------------

function runCheck() {
  const manifest = loadManifest();
  const missing = [];
  for (const { cat, p } of allPages(manifest)) {
    for (const f of pageFiles(cat, p)) {
      if (!exists(f)) missing.push(f);
    }
  }
  if (missing.length) {
    console.log(`Missing ${missing.length} file(s):`);
    for (const m of missing) console.log(`  - ${m}`);
    process.exit(1);
  }
  console.log('All pages scaffolded');
  process.exit(0);
}

// ---------------------------------------------------------------------------
// Command: scaffold
// ---------------------------------------------------------------------------

function runScaffold(force) {
  const manifest = loadManifest();
  const created = [];
  const skipped = [];
  for (const { cat, p } of allPages(manifest)) {
    const files = pageFiles(cat, p);
    for (const f of files) {
      // types.ts is only generated once per category (skip if it already exists).
      if (path.basename(f) === 'types.ts' && exists(f)) {
        skipped.push(f);
        continue;
      }
      const content = renderFor(f, cat, p);
      const r = writeIfMissing(f, content, force);
      if (r.skipped) skipped.push(r.file);
      else created.push(r.file);
    }
  }
  console.log(`Created ${created.length} file(s), skipped ${skipped.length} existing.`);
  for (const c of created) console.log(`  + ${c}`);
}

// ---------------------------------------------------------------------------
// CLI
// ---------------------------------------------------------------------------

function main() {
  const args = process.argv.slice(2);
  const cmd = args[0];
  const force = args.includes('--force');

  switch (cmd) {
    case 'list': {
      printTree(loadManifest());
      break;
    }
    case 'check': {
      runCheck();
      break;
    }
    case 'scaffold': {
      runScaffold(force);
      break;
    }
    default: {
      console.error('Usage: node generate.js <list|check|scaffold> [--force]');
      process.exit(2);
    }
  }
}

main();
