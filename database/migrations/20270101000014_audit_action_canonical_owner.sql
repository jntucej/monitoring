-- 20270101000014_audit_action_canonical_owner.sql
-- ============================================================================
-- Single, monotonic owner of the audit_logs.action CHECK constraint.
--
-- The constraint has historically been spliced/dropped/recreated across ~10
-- migrations, so the live schema often ended up with NO active check (an
-- audit_logs row with action='PG_TEST' was proof the check was not biting).
-- This migration is the owner-of-record: it establishes the COMPLETE canonical
-- action set (union of every action array in the lineage + the historical
-- values already present in audit_logs data) as a single CHECK, and is the ONLY
-- migration that should ever change it going forward. All older
-- drop/recreate blocks replay harmlessly into this one.
--
-- Monotonic: actions are only ever ADDED here (never removed), so re-replay of
-- this migration is idempotent and the one-row-per-action regression test
-- (check-audit-constraint.sh / tests/) stays meaningful.
-- ============================================================================

