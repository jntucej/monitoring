/* ═══════════════════════════════════════════════════════════════
   COMMANDS
   ═══════════════════════════════════════════════════════════════ */
async function cmdNew(role, args) {
  if (!role) die("usage: new <role> [flags]");

  const ctx = {
    role,
    title:      args.title ?? `${titleCase(role)} Dashboard`,
    route:      args.route ?? `/${kebab(role)}`,
    group:      args.group ?? "(approver)",
    minTier:    Number(args["min-tier"] ?? 60),
    api:        args.api ?? `/api/${kebab(role)}/dashboard`,
    kpis:       Math.min(6, Math.max(3, Number(args.kpis ?? 4))),
    widgets:    Math.min(6, Math.max(0, Number(args.widgets ?? 3))),
    pollProfile: args.poll ?? "standard",
    // Map the profile name to the actual POLL_INTERVALS key.
    pollKey:    { standard: "normal", fast: "fast", slow: "slow", realtime: "realtime",
                   background: "background" }[args.poll ?? "standard"],
    force:      Boolean(args.force),
    dryRun:     Boolean(args["dry-run"]),
  };

  head(`Scaffolding dashboard: ${ctx.title}`);
  info(`role=${ctx.role} route=${ctx.route} tier=${ctx.minTier} api=${ctx.api}`);

  const base = `src/app/${ctx.group}${ctx.route}`;

  await writeFileSafe(join(base, "page.tsx"), pageTemplate(ctx), ctx);
  if (ctx["with-loading"] !== "false") {
    await writeFileSafe(join(base, "loading.tsx"), loadingTemplate(), ctx);
  }
  if (ctx["with-error"] !== "false") {
    await writeFileSafe(join(base, "error.tsx"), errorTemplate(ctx.role), ctx);
  }
  if (ctx["with-layout"]) {
    await writeFileSafe(join(base, "layout.tsx"), layoutTemplate(ctx), ctx);
  }

  ok(`\nDashboard scaffolded at ${base}`);
  info(`Run \`node scripts/dashboard-doctor.mjs audit ${base}\` to verify zero issues.`);
}

async function cmdList() {
  head("Existing dashboards");
  const { readdir } = await import("node:fs/promises");
  const groups = ["(admin)", "(approver)", "(sysadmin)", "(operator)", "(student)", "(supervisor)", "(parent)"];
  for (const g of groups) {
    const base = `src/app/${g}`;
    if (!(await pathExists(base))) continue;
    info(`${g}`);
    for (const role of await readdir(base).catch(() => [])) {
      if (role.startsWith("_") || role.startsWith(".")) continue;
      console.log(`    ${role}`);
    }
  }
}

