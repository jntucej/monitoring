import { mkdir, writeFile, access } from "node:fs/promises";
import { constants } from "node:fs";
import { dirname, join } from "node:path";

/* ─────────────────────────── ANSI ─────────────────────────── */
const C = {
  red:    (s) => `\x1b[31m${s}\x1b[0m`,
  green:  (s) => `\x1b[32m${s}\x1b[0m`,
  yellow: (s) => `\x1b[33m${s}\x1b[0m`,
  cyan:   (s) => `\x1b[36m${s}\x1b[0m`,
  dim:    (s) => `\x1b[2m${s}\x1b[0m`,
  bold:   (s) => `\x1b[1m${s}\x1b[0m`,
};
const die  = (m) => { console.error(C.red(`✗ ${m}`)); process.exit(1); };
const ok   = (m) => console.log(C.green(`✓ ${m}`));
const warn = (m) => console.log(C.yellow(`! ${m}`));
const info = (m) => console.log(C.dim(`  ${m}`));
const head = (m) => console.log(C.bold(C.cyan(`\n▸ ${m}`)));

/* ─────────────────────────── helpers ──────────────────────── */
const pascal    = (s) => s.split(/[-_\s]+/).map((w) => w[0].toUpperCase() + w.slice(1)).join("");
const camel     = (s) => { const p = pascal(s); return p[0].toLowerCase() + p.slice(1); };
const titleCase = (s) => s.split(/[-_\s]+/).map((w) => w[0].toUpperCase() + w.slice(1)).join(" ");
const kebab     = (s) => s.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`).replace(/^-/, "");

async function pathExists(p) {
  try { await access(p, constants.F_OK); return true; } catch { return false; }
}

async function writeFileSafe(absPath, content, { force = false, dryRun = false } = {}) {
  const exists = await pathExists(absPath);
  if (exists && !force) { warn(`skip (exists): ${absPath}`); return false; }
  if (dryRun) { info(`would write: ${absPath}`); return true; }
  await mkdir(dirname(absPath), { recursive: true });
  await writeFile(absPath, content, "utf8");
  ok(`wrote: ${absPath}`);
  return true;
}

function parseArgs(argv) {
  const args = { _: [] };
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (a.startsWith("--")) {
      const key = a.slice(2);
      const next = argv[i + 1];
      if (next && !next.startsWith("--")) { args[key] = next; i++; }
      else { args[key] = true; }
    } else { args._.push(a); }
  }
  return args;
}

