/* ═══════════════════════════════════════════════════════════════
   DISPATCH
   ═══════════════════════════════════════════════════════════════ */
async function main() {
  const args = parseArgs(process.argv.slice(2));
  let cmd = args._[0] ?? "help";

  // If the first positional isn't a known command, assume the user wants
  // `new <role>` so e.g. `node scaffold-dashboard-v2.mjs warden` works.
  if (["new", "list", "help"].indexOf(cmd) < 0 && args._.length > 0) {
    cmd = "new";
  }

  switch (cmd) {
    case "new":  await cmdNew(args._[0], args); break;
    case "list": await cmdList(); break;
    case "help":
    case undefined:
      cmdHelp(); break;
    default:
      die(`unknown command: ${cmd}`);
  }
}

main().catch((err) => {
  console.error(C.red(`✗ ${err.message}`));
  process.exit(1);
});
