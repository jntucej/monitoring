//   ✓ POLL_INTERVALS from @/config/app-constants (R15 — no magic numbers)
//   ✓ WidgetBoundary per widget (R16 — one failure can't blank page)
//   ✓ fmtRelative from @/lib/formatters (R12 — no local timeAgo)
//   ✓ dynamic() recharts import (R19 — no eager bundle)
//   ✓ useMemo on every derived array (R25)
//   ✓ aria-live on KPI numbers (R20)
//   ✓ toasts via useUIStore (R5 — never alert)
//   ✓ typed interfaces (no \`any\`)
//   ✓ DevContactStrip at bottom
//   ✓ ConditionalAlert for role-scoped alerts
//   ✓ PageHeader with breadcrumb
