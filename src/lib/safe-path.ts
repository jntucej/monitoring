import path from "node:path";
import { BadRequestError } from "@/server/http/errors";

/**
 * Path-safety helpers (Part 6 — file upload / document hardening).
 *
 * Two layers, both must pass:
 *   1. An allowlist regex rejects every character that path resolution can
 *      reinterpret: / \ . % NUL, whitespace, bidi controls, etc.
 *   2. A resolve-and-contain check against the actual root directory.
 *
 * This kills path traversal by construction: there is no character in an
 * allowlisted segment that `path.resolve` can use to escape the root, so the
 * regex is the primary defense and the containment check is belt-and-braces
 * for typos in the regex (regex-only would defeat %2e%2e%2f variants; the
 * decode happens in the HTTP layer BEFORE we ever reach here, so a decoded
 * `../` also fails the regex).
 */

/** Permissive identifier charset for generated ticket numbers (allowlist). */
export const TICKET_PATTERN = /^[A-Z0-9_-]{4,64}$/i;

/** Strict identifier charset for DB-generated UUIDs and our own names. */
const SEGMENT_PATTERN = /^[A-Za-z0-9._-]{1,128}$/;

/**
 * Validate a ticket number before it ever touches the filesystem.
 * Tickets are generated by the app as `PREFIX-YYYY-NNNN` (e.g. HP-2026-0001);
 * the allowlist above matches exactly that shape and nothing else.
 */
export function assertSafeTicket(ticket: string): void {
  if (!TICKET_PATTERN.test(ticket)) {
    throw new BadRequestError("invalid ticket number");
  }
}

/**
 * Resolve `root + segments`, refusing anything that escapes root.
 * Every segment must match the strict identifier allowlist.
 */
export function safeJoin(root: string, ...segments: string[]): string {
  for (const seg of segments) {
    if (
      !SEGMENT_PATTERN.test(seg) ||
      seg === "." ||
      seg === ".." ||
      /^[.]/.test(seg)
    ) {
      throw new BadRequestError("invalid path segment");
    }
  }

  const resolvedRoot = path.resolve(root);
  const candidate = path.resolve(resolvedRoot, ...segments);
  const rel = path.relative(resolvedRoot, candidate);
  if (rel.startsWith("..") || path.isAbsolute(rel)) {
    throw new BadRequestError("path escapes root");
  }
  return candidate;
}
